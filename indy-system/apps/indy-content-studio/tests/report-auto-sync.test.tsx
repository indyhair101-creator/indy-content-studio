import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { createEmptyDashboardState } from "../features/domain/create-empty-state";
import { ReportConnectionsPanel } from "../features/reports/components/ReportConnectionsPanel";
const fixture = vi.hoisted(() => ({ state: null as ReturnType<typeof createEmptyDashboardState> | null, mutate: vi.fn() }));
vi.mock("../features/data/DashboardDataProvider", () => ({ useDashboardData: () => ({ state: fixture.state, status: "ready", mutate: fixture.mutate }) }));
afterEach(() => vi.unstubAllGlobals());
describe("report explicit sync", () => {
  it.each([false, true])("does not fetch on visits, remount, range changes or focus (stale data: %s)", async (stale) => {
    fixture.state = createEmptyDashboardState();
    if (stale) fixture.state.reporting = { connections: [], publications: [], savedReports: [], observations: [{ id: "saved", publicationId: "post", fetchedAt: "2025-01-01T00:00:00Z", source: "api", sourceLabel: "Facebook", scope: "lifetime", period: null, traffic: "organic", metrics: { views: 100 }, averageWatchWeight: null, retention: null }] };
    const fetcher = vi.fn().mockResolvedValue(Response.json({ connections: [], publications: [], observations: [], warnings: [], truncated: false }));
    vi.stubGlobal("fetch", fetcher);
    const legacyProps = { autoSync: true };
    const view = render(<ReportConnectionsPanel {...legacyProps} range={{ start: "2026-10-01", end: "2026-10-10" }} />);
    await act(async () => {});
    view.rerender(<ReportConnectionsPanel {...legacyProps} range={{ start: "2026-09-01", end: "2026-09-30" }} />);
    fireEvent(window, new Event("focus"));
    fireEvent(document, new Event("visibilitychange"));
    view.unmount();
    render(<ReportConnectionsPanel {...legacyProps} range={{ start: "2026-09-01", end: "2026-09-30" }} />);
    await act(async () => {});
    expect(fetcher).not.toHaveBeenCalled();
  });
  it("fetches only on button click and saves metrics without touching calendar contents", async () => {
    fixture.state = createEmptyDashboardState();
    fixture.mutate.mockImplementation(async update => { fixture.state = update(fixture.state); });
    const fetcher = vi.fn(async () => Response.json({ connections: [], publications: [{ id: "real", contentId: null }], observations: [{ id: "metric", publicationId: "real", fetchedAt: new Date().toISOString(), metrics: { views: 100 } }], warnings: [], truncated: false }));
    vi.stubGlobal("fetch", fetcher);
    const { rerender } = render(<ReportConnectionsPanel />);
    expect(fetcher).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole("button", { name: "ดึงข้อมูลล่าสุดจากโซเชียล" }));
    await waitFor(() => expect(fixture.state?.reporting?.observations[0]?.metrics.views).toBe(100));
    expect(fixture.state?.contents).toEqual([]);
    expect(fetcher).toHaveBeenCalledTimes(1);
    rerender(<ReportConnectionsPanel />);
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect(screen.getByRole("button", { name: "ดึงข้อมูลล่าสุดจากโซเชียล" })).toBeInTheDocument();
  });
  it("locks repeated clicks and preserves saved data after a failed request", async () => {
    fixture.state = createEmptyDashboardState();
    fixture.state.reporting = { connections: [], publications: [], savedReports: [], observations: [{ id: "saved", publicationId: "post", fetchedAt: "2025-01-01T00:00:00Z", source: "api", sourceLabel: "Facebook", scope: "lifetime", period: null, traffic: "organic", metrics: { views: 100 }, averageWatchWeight: null, retention: null }] };
    const before = structuredClone(fixture.state);
    fixture.mutate.mockClear();
    let resolve!: (response: Response) => void;
    const fetcher = vi.fn(() => new Promise<Response>(done => { resolve = done; }));
    vi.stubGlobal("fetch", fetcher);
    const range = { start: "2026-10-01", end: "2026-10-10" };
    render(<ReportConnectionsPanel range={range} />);
    const button = screen.getByRole("button", { name: "ดึงข้อมูลล่าสุดจากโซเชียล" });
    fireEvent.click(button);
    fireEvent.click(button);
    expect(button).toBeDisabled();
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect(fetcher).toHaveBeenCalledWith("/api/reports/sync", expect.objectContaining({ method: "POST", body: JSON.stringify({ range }) }));
    await act(async () => resolve(new Response(null, { status: 503 })));
    await waitFor(() => expect(button).toBeEnabled());
    expect(screen.getByRole("status")).toHaveTextContent("อัปเดตข้อมูลไม่สำเร็จ");
    expect(fixture.state).toEqual(before);
    expect(fixture.mutate).not.toHaveBeenCalled();
  });
});
